def build():
    doc = Document()
    sec = doc.sections[0]
    sec.top_margin = Cm(2.2)
    sec.bottom_margin = Cm(2.2)
    sec.left_margin = Cm(2.5)
    sec.right_margin = Cm(2.5)

    style = doc.styles["Normal"]
    style.font.name = "Microsoft YaHei"
    style.font.size = Pt(10.5)

    cover(doc)
    chapter_politics(doc)

    # ---- politics speech
    h2(doc, "三、五分钟演讲稿：制度如何影响发展（对应上述选答）")
    para(doc, "下面这份稿子按五分钟设计，括号内是时间提示，方便课堂上对着讲。",
         size=10, color=GREY, space_after=6)
    total = sum(len(t) + len(p) for t, p in SPEECH_POLITICS)
    speech_block(doc, "从高铁与脱贫攻坚看中国的政治制度", SPEECH_POLITICS,
                 "这套制度最突出的能力是集中力量办长周期的大事；最需要补足的能力是"
                 "听见不同的声音并且及时纠错。", total)

    chapter_environment(doc)

    # ---- environment speech
    h2(doc, "三、五分钟演讲稿：绿水青山就是金山银山（对应上述选答）")
    para(doc, "下面这份稿子同样按五分钟设计，括号内是时间提示。",
         size=10, color=GREY, space_after=6)
    total2 = sum(len(t) + len(p) for t, p in SPEECH_ENV)
    speech_block(doc, "绿水青山就是金山银山：含义、理由与两个条件", SPEECH_ENV,
                 "保护环境不是不发展，而是换一种更能持续的发展方式；"
                 "但这个“转化”需要制度、技术和资金一起推动。", total2)

    appendix(doc)

    out = "政治与环境资源_基础题与讨论题解答_2026秋季.docx"
    doc.save(out)
    print("saved docx, speech1 chars:", total, "speech2 chars:", total2)
    print("speech1 chars:", total, "speech2 chars:", total2)
    return out


if __name__ == "__main__":
    build()
